#!/usr/bin/env python3
"""Multi-seed APidopnetwork-regeneration comparison on E23 gene panel.

This experiment fixes the best-performing recurrent mechanism from the input
ablation:

    FiNN-RNN: H_{k-1}, P_k, time_k -> H_k

and compares the training data source:

    no augmentation
    bootstrap paired trajectories
    harmonic parasite regeneration
    APidopnetwork parasite regeneration

The APidopnetwork augmentation follows the manuscript logic: complete host
gene trajectories are regenerated from a shrinkage multivariate Gaussian law,
then paired parasite trajectories are generated by

    P(t) = B_s [H(t) sin(omega t)] + B_c [H(t) cos(omega t)]
           + a sin(omega t) + b cos(omega t) + residual.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import RidgeCV

from run_mahpic_finn_input_ablation import fit_model, forecast, mse_r2, split_target_condition
from run_mahpic_gene_panel_input_ablation import (
    OMEGA,
    RIDGE_ALPHAS,
    fit_apidopnetwork,
    fit_gene_panel_sequences,
    predict_apidopnetwork,
    regenerate_host_gaussian,
    select_gene_panel,
)
from run_mahpic_regeneration_prediction import DEFAULT_TIME_GRID, ModuleSequences, load_dataset, subset_dataset


METHOD_LABELS = {
    "none": "No augmentation",
    "bootstrap": "Bootstrap augmentation",
    "harmonic": "Harmonic regeneration",
    "apidopnetwork": "APidopnetwork regeneration",
}


def ensure_dirs(out_dir: Path) -> tuple[Path, Path]:
    table_dir = out_dir / "tables"
    fig_dir = out_dir / "figures"
    table_dir.mkdir(parents=True, exist_ok=True)
    fig_dir.mkdir(parents=True, exist_ok=True)
    return table_dir, fig_dir


def residual_cov(residual: np.ndarray, dim: int) -> np.ndarray:
    cov = np.cov(residual, rowvar=False)
    cov = np.atleast_2d(cov) + 1e-5 * np.eye(dim)
    return cov


def harmonic_design(host: np.ndarray, time: np.ndarray) -> np.ndarray:
    n_seq, n_time, _ = host.shape
    sin_t = np.sin(OMEGA * time)[None, :, None]
    cos_t = np.cos(OMEGA * time)[None, :, None]
    return np.tile(np.concatenate([sin_t, cos_t], axis=2), (n_seq, 1, 1))


def fit_harmonic_model(host: np.ndarray, parasite: np.ndarray, time: np.ndarray) -> tuple[RidgeCV, np.ndarray]:
    design = harmonic_design(host, time).reshape(-1, 2)
    target = parasite.reshape(-1, parasite.shape[-1])
    model = RidgeCV(alphas=RIDGE_ALPHAS, fit_intercept=False)
    model.fit(design, target)
    residual = target - model.predict(design)
    return model, residual_cov(residual, parasite.shape[-1])


def predict_harmonic(model: RidgeCV, host: np.ndarray, time: np.ndarray) -> np.ndarray:
    design = harmonic_design(host, time).reshape(-1, 2)
    pred = model.predict(design)
    return pred.reshape(host.shape[0], host.shape[1], -1)


def bootstrap_pair(
    rng: np.random.Generator,
    host_train: np.ndarray,
    parasite_train: np.ndarray,
    n_generated: int,
    noise_scale: float,
) -> tuple[np.ndarray, np.ndarray]:
    idx = rng.integers(0, host_train.shape[0], size=n_generated)
    host_noise = noise_scale * rng.normal(size=(n_generated, host_train.shape[1], host_train.shape[2]))
    parasite_noise = noise_scale * rng.normal(size=(n_generated, parasite_train.shape[1], parasite_train.shape[2]))
    return host_train[idx] + host_noise, parasite_train[idx] + parasite_noise


def generate_pair(
    train_mod: ModuleSequences,
    method: str,
    seed: int,
    args: argparse.Namespace,
) -> tuple[np.ndarray, np.ndarray, int]:
    if method == "none":
        return train_mod.host, train_mod.parasite, 0

    rng = np.random.default_rng(seed + 1201 + 17 * len(method))
    if method == "bootstrap":
        host_gen, parasite_gen = bootstrap_pair(
            rng,
            train_mod.host,
            train_mod.parasite,
            args.n_generated,
            args.bootstrap_noise,
        )
    elif method == "harmonic":
        host_gen = regenerate_host_gaussian(
            rng,
            train_mod.host,
            args.n_generated,
            args.host_gaussian_shrinkage,
        )
        model, cov = fit_harmonic_model(train_mod.host, train_mod.parasite, train_mod.time_grid)
        parasite_gen = predict_harmonic(model, host_gen, train_mod.time_grid)
        residual = rng.multivariate_normal(
            np.zeros(train_mod.parasite.shape[-1]),
            cov,
            size=args.n_generated * len(train_mod.time_grid),
        ).reshape(args.n_generated, len(train_mod.time_grid), train_mod.parasite.shape[-1])
        parasite_gen = parasite_gen + residual
    elif method == "apidopnetwork":
        host_gen = regenerate_host_gaussian(
            rng,
            train_mod.host,
            args.n_generated,
            args.host_gaussian_shrinkage,
        )
        model, cov = fit_apidopnetwork(
            train_mod.host,
            train_mod.parasite,
            train_mod.time_grid,
            regressor=args.apidop_regressor,
            alpha=args.apidop_alpha,
            l1_ratio=args.apidop_l1_ratio,
        )
        parasite_gen = predict_apidopnetwork(model, host_gen, train_mod.time_grid)
        residual = rng.multivariate_normal(
            np.zeros(train_mod.parasite.shape[-1]),
            cov,
            size=args.n_generated * len(train_mod.time_grid),
        ).reshape(args.n_generated, len(train_mod.time_grid), train_mod.parasite.shape[-1])
        parasite_gen = parasite_gen + residual
    else:
        raise ValueError(method)

    host_aug = np.concatenate([train_mod.host, host_gen], axis=0)
    parasite_aug = np.concatenate([train_mod.parasite, parasite_gen], axis=0)
    return host_aug, parasite_aug, args.n_generated


def evaluate_seed_fold(train_mod, test_mod, fold: str, seed: int, args: argparse.Namespace) -> list[dict[str, float | int | str]]:
    rows: list[dict[str, float | int | str]] = []
    target_test, condition_test = split_target_condition(test_mod, args.target)
    for method in args.methods:
        host_train, parasite_train, n_generated = generate_pair(train_mod, method, seed, args)
        aug_mod = ModuleSequences(train_mod.experiment, train_mod.animals, train_mod.time_grid, host_train, parasite_train)
        target_train, condition_train = split_target_condition(aug_mod, args.target)
        for train_window in args.train_windows:
            future_slice = slice(train_window, len(train_mod.time_grid))
            model, x_scaler, y_scaler = fit_model(
                target_train,
                condition_train,
                train_mod.time_grid,
                "finn",
                args.cell,
                seed + 1000 + len(fold) + train_window + 31 * len(method),
                args.hidden_dim,
                args.epochs,
                args.batch_size,
                args.lr,
            )
            pred = forecast(
                model,
                x_scaler,
                y_scaler,
                target_test,
                condition_test,
                train_mod.time_grid,
                "finn",
                train_window,
            )
            mse, r2 = mse_r2(target_test[:, future_slice, :], pred[:, future_slice, :])
            rows.append(
                {
                    "seed": seed,
                    "fold": fold,
                    "target": args.target,
                    "method": method,
                    "method_label": METHOD_LABELS[method],
                    "input_mode": "finn",
                    "cell_type": args.cell,
                    "observed_time_points": int(train_window),
                    "future_time_points": int(len(train_mod.time_grid) - train_window),
                    "mse": mse,
                    "r2": r2,
                    "n_original_train_trajectories": int(train_mod.host.shape[0]),
                    "n_generated_trajectories": int(n_generated),
                }
            )
    return rows


def summarize(raw: pd.DataFrame) -> pd.DataFrame:
    summary = (
        raw.groupby(["target", "method", "method_label", "input_mode", "cell_type", "observed_time_points"], sort=False)
        .agg(
            mse_mean=("mse", "mean"),
            mse_sd=("mse", "std"),
            mse_median=("mse", "median"),
            r2_mean=("r2", "mean"),
            r2_sd=("r2", "std"),
            n_runs=("mse", "count"),
        )
        .reset_index()
    )
    best = summary.groupby("observed_time_points")["mse_mean"].transform("min")
    summary["is_best_mean"] = np.isclose(summary["mse_mean"], best)
    return summary


def write_tables(summary: pd.DataFrame, raw: pd.DataFrame, table_dir: Path) -> None:
    windows = sorted(summary["observed_time_points"].unique(), reverse=True)
    lines = [
        "\\begin{tabular}{l" + "c" * len(windows) + "}",
        "\\toprule",
        "Training data & " + " & ".join([f"first {int(w)} TP" for w in windows]) + " \\\\",
        "\\midrule",
    ]
    for method in ["none", "bootstrap", "harmonic", "apidopnetwork"]:
        cells = []
        for window in windows:
            row = summary[(summary["method"] == method) & (summary["observed_time_points"] == window)].iloc[0]
            text = f"{float(row['mse_mean']):.4f} ({float(row['mse_sd']):.4f})"
            if bool(row["is_best_mean"]):
                text = f"\\textbf{{{text}}}"
            cells.append(text)
        lines.append(f"{METHOD_LABELS[method]} & " + " & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    (table_dir / "gene_panel_finn_augmentation_comparison.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    win_table = (
        raw.groupby(["observed_time_points", "seed", "fold"], sort=False)
        .apply(lambda g: g.loc[g["mse"].idxmin(), "method"], include_groups=False)
        .reset_index(name="winner")
        .groupby(["observed_time_points", "winner"])
        .size()
        .reset_index(name="wins")
    )
    win_table.to_csv(table_dir / "gene_panel_finn_augmentation_wins.csv", index=False)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=Path, default=Path("data/mahpic_geo"))
    parser.add_argument("--out-dir", type=Path, default=Path("results/mahpic_gene_panel_augmentation_multiseed_e23_host_target_rnn"))
    parser.add_argument("--target", choices=["host", "parasite"], default="host")
    parser.add_argument("--methods", nargs="+", default=["none", "bootstrap", "harmonic", "apidopnetwork"], choices=list(METHOD_LABELS))
    parser.add_argument("--n-panel-genes", type=int, default=20)
    parser.add_argument("--top-fraction", type=float, default=0.05)
    parser.add_argument("--n-generated", type=int, default=160)
    parser.add_argument("--host-gaussian-shrinkage", type=float, default=0.35)
    parser.add_argument("--bootstrap-noise", type=float, default=0.05)
    parser.add_argument(
        "--apidop-regressor",
        choices=["ridge", "elasticnet", "lasso", "fixed_lasso", "fixed_elasticnet"],
        default="ridge",
    )
    parser.add_argument("--apidop-alpha", type=float, default=None)
    parser.add_argument("--apidop-l1-ratio", type=float, default=0.5)
    parser.add_argument("--train-windows", type=int, nargs="+", default=[5, 4])
    parser.add_argument("--cell", choices=["RNN", "LSTM", "GRU"], default="RNN")
    parser.add_argument("--seeds", type=int, nargs="+", default=[2024, 2025, 2026])
    parser.add_argument("--hidden-dim", type=int, default=28)
    parser.add_argument("--epochs", type=int, default=300)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--lr", type=float, default=0.01)
    parser.add_argument("--time-grid", type=float, nargs="+", default=list(DEFAULT_TIME_GRID))
    args = parser.parse_args()

    table_dir, _ = ensure_dirs(args.out_dir)
    cache_dir = args.out_dir / "cache"
    cache_dir.mkdir(parents=True, exist_ok=True)
    e23 = load_dataset("E23", args.data_dir, cache_dir)
    time_grid = np.asarray(args.time_grid, dtype=float)
    host_genes, host_stats = select_gene_panel(e23.host, args.n_panel_genes, args.top_fraction)
    parasite_genes, parasite_stats = select_gene_panel(e23.parasite, args.n_panel_genes, args.top_fraction)
    host_stats.to_csv(table_dir / "selected_host_gene_panel.csv", index=False)
    parasite_stats.to_csv(table_dir / "selected_parasite_gene_panel.csv", index=False)

    rows: list[dict[str, float | int | str]] = []
    for seed in args.seeds:
        for animal in sorted(e23.meta["animal"].unique()):
            train = subset_dataset(e23, e23.meta["animal"] != animal)
            test = subset_dataset(e23, e23.meta["animal"] == animal)
            train_mod, test_mod = fit_gene_panel_sequences(train, test, host_genes, parasite_genes, time_grid)
            rows.extend(evaluate_seed_fold(train_mod, test_mod, str(animal), seed, args))

    raw = pd.DataFrame(rows)
    summary = summarize(raw)
    raw.to_csv(table_dir / "gene_panel_finn_augmentation_raw.csv", index=False)
    summary.to_csv(table_dir / "gene_panel_finn_augmentation_summary.csv", index=False)
    write_tables(summary, raw, table_dir)
    metadata = {
        "target": args.target,
        "input_mode": "FiNN: H_{k-1}, P_k, time_k -> H_k",
        "cell": args.cell,
        "seeds": args.seeds,
        "methods": args.methods,
        "feature_mode": "raw_gene_panel",
        "n_panel_genes_per_species": args.n_panel_genes,
        "n_generated": args.n_generated,
        "apidop_regressor": args.apidop_regressor,
        "apidop_alpha": args.apidop_alpha,
        "apidop_l1_ratio": args.apidop_l1_ratio,
        "apidopnetwork_model": "P(t)=B_s[H(t)sin(omega t)]+B_c[H(t)cos(omega t)]+a sin(omega t)+b cos(omega t)",
    }
    (args.out_dir / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(summary.to_string(index=False))
    print(f"\nWrote results to {args.out_dir}")


if __name__ == "__main__":
    main()
